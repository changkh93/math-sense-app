import assert from 'node:assert/strict'
import { readFile, mkdir } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
const { chromium } = createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) })
const page = await browser.newPage({ viewport: { width: 1800, height: 1100 } })
page.setDefaultTimeout(90000)
const output = new URL(process.env.GAME_STUDIO_QA_OUTPUT || '../docs/collaboration/tasks/20260909-studio-turtle/verification/', import.meta.url)
await mkdir(output, { recursive: true })
const errors = []
page.on('pageerror', error => errors.push(error.message))
const runtime = async () => (await page.locator('iframe[title="Python 게임 실행 화면"]').elementHandle()).contentFrame()
async function run(source) {
  await page.locator('.cm-content').click()
  await page.keyboard.press(process.platform === 'darwin' ? 'Meta+a' : 'Control+a')
  await page.keyboard.insertText(source)
  await page.getByRole('button', { name: '실행', exact: true }).click()
}
async function finished() {
  await page.waitForFunction(() => document.querySelector('.pgs-run-status')?.classList.contains('exited') || document.querySelector('.pgs-run-status')?.classList.contains('error'))
  assert.equal(await page.locator('.pgs-run-status').getAttribute('class'), 'pgs-run-status exited', await page.locator('.pgs-console pre').innerText())
}
try {
  await page.goto(process.env.GAME_STUDIO_QA_URL || 'http://127.0.0.1:5179/dev/python-game-studio')
  await page.locator('.cm-content').waitFor()
  const house = await readFile(new URL('../public/python-game-examples/turtle/house.py', import.meta.url), 'utf8')
  await run(house)
  await finished()
  const frame = await runtime()
  await frame.evaluate(() => { window.turtleQaIdentity = 'same-interpreter' })
  const svg = frame.locator('#turtle-canvas')
  assert.equal(await svg.getAttribute('viewBox'), '-400 -300 800 600')
  assert.equal(await svg.locator('polygon[fill=deepskyblue]').count(), 1)
  assert.equal(await svg.locator('polygon').count(), 13)
  await svg.screenshot({ path: fileURLToPath(new URL('house.png', output)) })
  console.log('PASS house: supplied install/import, spaced colors, fills while pen-up, functions, circles, speed(15), final picture')

  const race = await readFile(new URL('../public/python-game-examples/turtle/race.py', import.meta.url), 'utf8')
  await run('import random\nrandom.seed(7)\n' + race + '\nimport json\nprint("RACE_RESULT:" + json.dumps([[t.xcor(), t.ycor()] for t in turtles]))')
  await frame.waitForFunction(() => document.querySelectorAll('#turtle-canvas [data-turtle]').length === 5)
  const racer = frame.locator('[data-turtle="1"]')
  const before = await racer.getAttribute('transform')
  await frame.waitForFunction(value => document.querySelector('[data-turtle="1"]')?.getAttribute('transform') !== value, before)
  assert.equal(await svg.getByText('거북이 승리', { exact: false }).count(), 0)
  await svg.screenshot({ path: fileURLToPath(new URL('race-running.png', output)) })
  await finished()
  const text = await page.locator('.pgs-console pre').innerText()
  const positions = JSON.parse(text.split('RACE_RESULT:')[1].trim())
  const winner = positions.findIndex(([x]) => x >= 240)
  assert.equal(await svg.locator('text').last().getAttribute('fill'), ['blue', 'pink', 'purple', 'red'][winner])
  assert.match(await svg.locator('text').last().textContent(), /거북이 승리/)
  assert.equal(await frame.evaluate(() => window.turtleQaIdentity), 'same-interpreter')
  await svg.screenshot({ path: fileURLToPath(new URL('race-finished.png', output)) })
  console.log('PASS race: visible movement, four turtles, fractional lines, Korean title/winner, original winner semantics, warm engine')

  await run('import turtle as t\nt.speed(1)\nfor i in range(50):\n    t.forward(100)\n    t.right(90)\n')
  await svg.waitFor()
  await page.getByRole('button', { name: '정지', exact: true }).click()
  await svg.waitFor({ state: 'detached' })
  await run('import turtle as t\nprint("FRESH", t.pos(), t.Screen().bgcolor())\nt.speed(0)\nt.color("red")\nt.circle(40)\nt.done()')
  await finished()
  assert.match(await page.locator('.pgs-console pre').innerText(), /FRESH \(0.0, 0.0\) white/)
  assert.equal(await svg.locator('polygon').count(), 0)
  console.log('PASS stop cancels animation; standard turtle starts fresh; speed(0)/done retain drawing')

  await run('print("PLAIN_AFTER_TURTLE")')
  await finished()
  assert.equal(await svg.count(), 0)
  assert.match(await page.locator('.pgs-console pre').innerText(), /PLAIN_AFTER_TURTLE/)
  await run('import pygame\npygame.init()\npygame.display.set_mode((320,240))\nprint("GAME_AFTER_TURTLE")\nwhile True:\n    pygame.event.get()\n    pygame.display.update()')
  await page.waitForFunction(() => document.querySelector('.pgs-console pre')?.textContent.includes('GAME_AFTER_TURTLE'))
  assert.equal(await frame.locator('#canvas').isVisible(), true)
  await run('from turtle import *\ncolor("notacolor")')
  await page.waitForFunction(() => document.querySelector('.pgs-run-status')?.classList.contains('error'))
  assert.match(await page.locator('.pgs-console pre').innerText(), /TurtleGraphicsError/)
  assert.equal(await frame.evaluate(() => window.turtleQaIdentity), 'same-interpreter')
  assert.deepEqual(errors, [])
  console.log('PASS turtle → print → pygame → turtle error; interpreter reused, errors shown')
} finally { await browser.close() }
