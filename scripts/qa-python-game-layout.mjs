import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
const { chromium } = createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) })
const context = await browser.newContext({ viewport: { width: 1440, height: 960 } })
context.setDefaultTimeout(30000)
const page = await context.newPage()
const errors = []
page.on('pageerror', error => errors.push(error.message))
const box = selector => page.locator(selector).boundingBox()
const handle = name => page.getByRole('separator', { name, exact: true })
async function drag(name, dx, dy) {
  const r = await handle(name).boundingBox()
  await page.mouse.move(r.x + r.width / 2, r.y + r.height / 2)
  await page.mouse.down(); await page.mouse.move(r.x + r.width / 2 + dx, r.y + r.height / 2 + dy, { steps: 12 }); await page.mouse.up()
}
const files = '파일 탐색기 너비 조절', editor = '소스코드와 게임 화면 너비 조절', output = '출력·오류 영역 높이 조절'
try {
  await page.goto(process.env.GAME_STUDIO_QA_URL || 'http://127.0.0.1:5179/dev/python-game-studio')
  await page.locator('.cm-content').waitFor()
  await page.locator('.cm-content').click(); await page.keyboard.insertText('import pygame\npygame.init()\nscreen=pygame.display.set_mode((320,240))\nwhile True:\n    for event in pygame.event.get():\n        if event.type == pygame.MOUSEBUTTONDOWN: print("LAYOUT_CLICK")\n    screen.fill((20,80,90))\n    pygame.display.flip()\n')
  await page.getByRole('button', { name: '실행', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.pgs-run-status')?.textContent === '실행 중', null, { timeout: 90000 })
  const runtime = await (await page.locator('iframe[title="Python 게임 실행 화면"]').elementHandle()).contentFrame()
  const marker = await runtime.evaluate(() => window.qaLayoutMarker = crypto.randomUUID())
  const startFile = await box('.pgs-files')
  await drag(files, 90, 0)
  assert.ok((await box('.pgs-files')).width > startFile.width + 75)
  const startEditor = await box('.pgs-editor-pane')
  await drag(editor, -100, 0)
  assert.ok((await box('.pgs-editor-pane')).width < startEditor.width - 80)
  const startConsole = await box('.pgs-console')
  await drag(output, 0, -120)
  assert.ok((await box('.pgs-console')).height > startConsole.height + 100)
  assert.equal(await runtime.evaluate(() => window.qaLayoutMarker), marker)
  assert.equal(await page.locator('.pgs-run-status').innerText(), '실행 중')
  await page.frameLocator('iframe[title="Python 게임 실행 화면"]').locator('#canvas').click()
  await page.waitForFunction(() => document.querySelector('.pgs-console pre')?.textContent.includes('LAYOUT_CLICK'))
  console.log('PASS three drag boundaries resize panels; running game and mouse input remain intact')
  await page.screenshot({ path: '/tmp/metasense-pygame-layout.png' })
  const savedWidths = [(await box('.pgs-files')).width, (await box('.pgs-editor-pane')).width, (await box('.pgs-console')).height]
  await page.reload(); await page.locator('.cm-content').waitFor()
  await page.waitForTimeout(150)
  const restored = [(await box('.pgs-files')).width, (await box('.pgs-editor-pane')).width, (await box('.pgs-console')).height]
  restored.forEach((value, i) => assert.ok(Math.abs(value - savedWidths[i]) < 2))
  await handle(files).focus(); await page.keyboard.press('Home'); assert.equal(Math.round((await box('.pgs-files')).width), 120)
  await page.keyboard.press('ArrowRight'); assert.equal(Math.round((await box('.pgs-files')).width), 136)
  await handle(files).dblclick(); assert.equal(Math.round((await box('.pgs-files')).width), 210)
  await drag(editor, 1500, 0); assert.ok((await box('.pgs-preview-pane')).width >= 259)
  await drag(output, 0, -1500); assert.ok((await box('.pgs-game-frame')).height >= 159)
  assert.equal(await page.locator('.pgs-is-resizing').count(), 0)
  console.log('PASS size persistence, keyboard adjustment, double-click reset, minimum sizes and capture release')
  await page.setViewportSize({ width: 390, height: 844 }); await page.waitForTimeout(150)
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await drag(files, -50, 0)
  await handle('소스코드 영역 높이 조절').scrollIntoViewIfNeeded()
  const startMobile = await box('.pgs-editor-pane')
  await drag('소스코드 영역 높이 조절', 0, 80)
  assert.ok((await box('.pgs-editor-pane')).height >= startMobile.height + 70)
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  console.log('PASS narrow layout uses a vertical split between code and game without horizontal overflow')
  assert.deepEqual(errors, [])
} finally { await browser.close() }
