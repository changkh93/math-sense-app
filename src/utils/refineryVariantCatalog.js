export function getRefineryVariantSet(question) {
  if (!question) return null
  return REFINERY_VARIANT_CATALOG[question.sourceQuestionId || question.id] || null
}

export const REFINERY_SUPPORTED_UNIT_IDS = [
  APRIL_EVAL_UNIT_ID,
  MARCH_EVAL_UNIT_ID,
  MARCH_EVAL_G5_UNIT_ID,
  APRIL_EVAL_G5_UNIT_ID,
  MARCH_EVAL_G4_UNIT_ID,
  APRIL_EVAL_G4_UNIT_ID,
  MARCH_EVAL_G3_UNIT_ID,
  APRIL_EVAL_G3_UNIT_ID,
  APRIL_EVAL_M1_UNIT_ID,
  APRIL_EVAL_M2_UNIT_ID,
  APRIL_EVAL_M3_UNIT_ID
]

export function isRefinerySupportedQuestion(question) {
  if (!question) return false
  const unitId = question.unitId
  const id = question.id || ''
  
  return REFINERY_SUPPORTED_UNIT_IDS.includes(unitId) || 
    REFINERY_SUPPORTED_UNIT_IDS.some(supportedId => id.startsWith(`${supportedId}_q`))
}

// Backward compatibility
export const isAprilEvaluationQuestion = isRefinerySupportedQuestion

