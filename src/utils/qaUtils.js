export const getRandomNickname = (seed) => {
  if (!seed) return '탐험가';
  
  // 1. 수동 지정된 별명이 있는 경우 (중복 해결 등)
  if (NICKNAME_OVERRIDES[seed]) {
    return NICKNAME_OVERRIDES[seed];
  }

  // 2. Legacy 로직: 기존 학생들의 정체성 보호 (10x10 Sum Hash)
  let sum = 0;
  for (let i = 0; i < seed.length; i++) {
    sum += seed.charCodeAt(i);
  }

  const adj = LEGACY_ADJS[sum % 10];
  const animal = LEGACY_ANIMALS[Math.floor(sum / 10) % 10];
  
  return `${adj} ${animal}`;
};


