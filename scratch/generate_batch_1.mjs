async function generateBatch1() {
  for (const book of batch1_books) {
    const unitId = `reg_1776154036888_${chapterId}_unit_book_${book.number}`;
    
    // Create Unit document in top-level 'units' collection
    await db.collection('units').doc(unitId).set({
        id: unitId,
        docId: unitId,
        title: book.title,
        order: book.number,
        chapterId: chapterId, // Essential for filtering
        updatedAt: admin.firestore.FieldValue.serverTimestamp(),
        lastUpdated: admin.firestore.FieldValue.serverTimestamp()
      }, { merge: true });
    
    console.log(`Unit Created/Updated: ${book.title} (${unitId})`);

    // Add Quizzes
    for (let i = 0; i < book.quizzes.length; i++) {
      const q = book.quizzes[i];
      const quizId = `${unitId}_q${i + 1}`;
      
      const quizData = {
        id: quizId,
        docId: quizId,
        unitId: unitId,
        question: q.question,
        options: q.options.map(opt => ({
          text: opt,
          isCorrect: opt === q.answer
        })),
        answer: q.answer,
        hint: q.hint,
        score: 1,
        order: (i + 1) * 10,
        updatedAt: admin.firestore.FieldValue.serverTimestamp()
      };

      await db.collection('quizzes').doc(quizId).set(quizData);
      // console.log(`  Quiz Added: ${quizId}`);
    }
    console.log(`  Total 20 quizzes added for ${book.title}`);
  }
}

generateBatch1().catch(console.error);
