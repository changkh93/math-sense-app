// Function to fix titles in the hints to match the DB order
function fixHintTitle(hintText, actualIndex) {
  const problemNum = (actualIndex + 1).toString().padStart(2, '0');
  return hintText.replace(/### \*\*문제 \d+\*\*/, `### **문제 ${problemNum}**`);
}

async function updateHints() {
  console.log(`\n--- Updating Hints for Unit: ${unitId} (6th Grade) ---`);
  try {
    const snap = await db.collection('quizzes')
      .where('unitId', '==', unitId)
      .get();
    
    if (snap.size !== 25) {
      console.warn(`Warning: Found ${snap.size} quizzes instead of 25.`);
    }

    const quizzes = snap.docs.map(doc => ({
      id: doc.id,
      ...doc.data()
    })).sort((a, b) => (a.order || 0) - (b.order || 0));

    const batch = db.batch();
    
    quizzes.forEach((q, idx) => {
      let hintText = unitHintsMapping[idx];
      if (hintText) {
        hintText = fixHintTitle(hintText, idx);
        console.log(`Mapping Corrected Hint to Quiz ID: ${q.id} (Order: ${q.order}, DB Pos: ${idx+1})`);
        batch.update(db.collection('quizzes').doc(q.id), {
          hint: hintText,
          updatedAt: admin.firestore.FieldValue.serverTimestamp()
        });
      }
    });

    batch.update(db.collection('units').doc(unitId), {
      lastUpdated: admin.firestore.FieldValue.serverTimestamp()
    });

    await batch.commit();
    console.log("Successfully updated all hints for 6th-grade unit.");
  } catch (err) {
    console.error("Error updating hints:", err.message);
  }
}

updateHints();
