async function updateQuizzes() {
  console.log(`\n--- Updating Quizzes for Unit: ${unitId} ---`);
  const quizzesRef = db.collection('quizzes');
  const snap = await quizzesRef.where('unitId', '==', unitId).get();
  
  for (const doc of snap.docs) {
    const data = doc.data();
    // Match based on a heuristic (e.g., question content or order)
    // For simplicity in this script, let's use the ID suffix if it matches our keys
    // In a real scenario, we'd be more precise.
    let key = null;
    if (data.id.includes('_q1_')) key = 'q1';
    else if (data.id.includes('_q2_')) key = 'q2';
    else if (data.id.includes('_q3_')) key = 'q3';
    
    if (key && enhancements[key]) {
      console.log(`Updating ${data.id}...`);
      await doc.ref.update({
        hint: enhancements[key].hint,
        explanation: enhancements[key].explanation
      });
    }
  }
  console.log('Update complete.');
}

