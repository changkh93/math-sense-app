async function updateHints() {
  console.log(`\n--- Updating Hints for Unit: ${unitId} ---`);
  try {
    const snap = await db.collection('quizzes')
      .where('unitId', '==', unitId)
      .get();
    
    if (snap.size !== 25) {
      console.warn(`Warning: Found ${snap.size} quizzes instead of 25. Proceeding with mapping...`);
    }

    const quizzes = snap.docs.map(doc => ({
      id: doc.id,
      ...doc.data()
    })).sort((a, b) => (a.order || 0) - (b.order || 0));

    const batch = db.batch();
    
    quizzes.forEach((q, idx) => {
      const hint = hints[idx];
      if (hint) {
        console.log(`Mapping Hint ${hint.order} to Quiz ID: ${q.id} (Order: ${q.order})`);
        batch.update(db.collection('quizzes').doc(q.id), {
          hint: hint.content,
          updatedAt: admin.firestore.FieldValue.serverTimestamp()
        });
      } else {
        console.warn(`No hint found for quiz at index ${idx}`);
      }
    });

    // Also update parent unit timestamp
    batch.update(db.collection('units').doc(unitId), {
      lastUpdated: admin.firestore.FieldValue.serverTimestamp()
    });

    await batch.commit();
    console.log("Successfully updated all hints and unit timestamp.");
  } catch (err) {
    console.error("Error updating hints:", err.message);
  }
}

updateHints();
